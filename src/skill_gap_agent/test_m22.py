"""M22 units: store-packaging consistency — icons, manifest, privacy policy
completeness, justification coverage, no stale references
(CHROMEWEBSTORE.md + docs/ are derived registers; these tests keep the
mirrors honest)."""

import json
import re
import struct
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[2]
EXTENSION_DIR = REPO_ROOT / "extension"

LIMITED_USE_STATEMENT = (
    "The use of information received from Chrome APIs will adhere to the "
    "Chrome Web Store User Data Policy, including the Limited Use "
    "requirements."
)


def _normalized(text: str) -> str:
    """Collapse wrapping/markdown markers so sentence-level asserts work."""
    return re.sub(r"\s+", " ", text.replace("> ", "")).strip()


def test_icons_exist_and_match_manifest():
    manifest = json.loads((EXTENSION_DIR / "manifest.json").read_text(encoding="utf-8"))
    for size, rel in manifest["icons"].items():
        path = EXTENSION_DIR / rel
        data = path.read_bytes()
        assert data[:8] == b"\x89PNG\r\n\x1a\n", f"{rel} is not a PNG"
        width, height = struct.unpack(">II", data[16:24])
        assert (width, height) == (int(size), int(size)), (rel, width, height)
    assert set(manifest["icons"]) == {"16", "48", "128"}
    assert manifest["action"]["default_icon"] == manifest["icons"]


def test_privacy_policy_completeness():
    policy = (REPO_ROOT / "docs" / "privacy-policy.md").read_text(encoding="utf-8")
    assert LIMITED_USE_STATEMENT in _normalized(policy)
    for name in ("OpenRouter", "DeepSeek", "Z.ai", "OpenAI", "GitHub"):
        assert name in policy, f"destination {name} missing from the policy"
    assert "China" in policy, "cross-border processing must be disclosed"
    assert "credential vault" in policy, "key storage must be described"
    assert "not directed at children under 16" in policy
    assert "never sold" in policy or "No sale" in policy.lower()


def test_justifications_cover_manifest():
    manifest = json.loads((EXTENSION_DIR / "manifest.json").read_text(encoding="utf-8"))
    register = (REPO_ROOT / "CHROMEWEBSTORE.md").read_text(encoding="utf-8")
    for perm in manifest["permissions"]:
        assert f'"{perm}"' in register, f"no justification for {perm}"
    for host in manifest["host_permissions"]:
        assert host in register, f"no justification for {host}"
    for match in manifest["content_scripts"][0]["matches"]:
        assert match in register, f"no justification for {match}"
    assert LIMITED_USE_STATEMENT in _normalized(register) or "Limited Use" in register
    assert "not affiliated with" in register.lower(), "LinkedIn disclaimer missing"
    assert "generated by AI" in register, "AI transparency notice missing"


def test_no_stale_references():
    for rel in (
        "CHROMEWEBSTORE.md", "THIRD-PARTY-NOTICES.md",
        "docs/index.md", "docs/privacy-policy.md", "README.md",
    ):
        text = (REPO_ROOT / rel).read_text(encoding="utf-8")
        base = (REPO_ROOT / rel).parent
        for target in re.findall(r"\]\(([^)#\s]+)\)", text):
            if "://" in target:
                continue
            assert (base / target).exists(), f"stale link {target!r} in {rel}"
